// Builds the "Grade Change Form" PDF for a request: the online version of the
// paper Official Grade Change Form, with every approval (name + date) filled in
// from our APPROVALS table instead of handwritten signatures.
// pdfkit is loaded only when a PDF is actually made (see below), so a problem
// with the PDF library can never stop the rest of the API from starting.

const NAVY = '#0b2a55';
const YELLOW = '#ffd43b';
const GREY = '#64748b';

const STAGE = { LECTURER: 'Lecturer', CHAIR: 'Chair of Department', DEAN: 'Dean', REGISTRAR: 'Registrar' };
const DECISION = {
  SUBMITTED: 'Submitted', RESUBMITTED: 'Resubmitted', APPROVED: 'Approved',
  RETURNED: 'Returned', REJECTED: 'Rejected', POSTED: 'Posted',
};
const STATUS = {
  WITH_CHAIR: 'With Chair', WITH_DEAN: 'With Dean', WITH_REGISTRAR: 'With Registrar',
  POSTED: 'Posted', RETURNED: 'Returned', REJECTED: 'Rejected',
};
const REASON = { ILLNESS: 'Illness', DEATH: 'Death', ARITHMETIC: 'Arithmetic', OTHER: 'Other' };

function when(date) {
  return new Date(date).toLocaleString('en-GB', {
    timeZone: 'Africa/Nairobi', day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
  });
}

// Everything since the last (re)submission = the approvals that count.
function latestRound(history) {
  let start = 0;
  history.forEach((h, i) => { if (h.decision === 'SUBMITTED' || h.decision === 'RESUBMITTED') start = i; });
  return history.slice(start);
}

function writeGradeChangeForm(stream, { request, evidence, history }) {
  const PDFDocument = require('pdfkit');
  const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: `${request.request_number} Grade Change Form` } });
  doc.pipe(stream);
  const left = 50;
  const width = doc.page.width - 100;

  // ---- Header band ----
  doc.rect(0, 0, doc.page.width, 80).fill(NAVY);
  doc.fillColor(YELLOW).font('Helvetica-Bold').fontSize(18).text('CHANGETRACK', left, 24);
  doc.fillColor('#ffffff').font('Helvetica').fontSize(10)
    .text('Grade Change Form  -  electronic approval record', left, 48);
  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(16).text(request.request_number, left, 100);
  doc.fillColor(GREY).font('Helvetica').fontSize(10)
    .text(`Status: ${STATUS[request.status]}     Department: ${request.department_name}`, left, 122);
  doc.moveDown(1.5);

  const heading = (text) => {
    doc.moveDown(0.8);
    doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(12).text(text, left);
    doc.moveTo(left, doc.y + 2).lineTo(left + width, doc.y + 2).strokeColor('#dbe3ef').stroke();
    doc.moveDown(0.5);
  };
  const row = (label, value) => {
    const y = doc.y;
    doc.fillColor(GREY).font('Helvetica').fontSize(10).text(label, left, y, { width: 140 });
    doc.fillColor('#1c2b45').font('Helvetica-Bold').fontSize(10).text(String(value), left + 150, y, { width: width - 150 });
    doc.moveDown(0.4);
  };

  // ---- Details ----
  heading('Student and course');
  row('Student', `${request.student_number}  -  ${request.student_name}`);
  row('Course / section', `${request.course_code}  -  Section ${request.section}`);
  row('Term', request.term);
  row('Lecturer', request.lecturer_name);

  heading('Grade change');
  row('Current grade', request.current_grade);
  row('New grade', request.new_grade);
  row('Reason', REASON[request.reason]);
  row('Justification', request.justification);

  heading('Supporting evidence');
  if (evidence.length === 0) row('Files', 'None');
  evidence.forEach((e, i) => row(i === 0 ? 'Files' : '', e.file_name));

  // ---- Approvals (the "signatures") ----
  heading('Approvals (fixed order: Lecturer -> Chair -> Dean -> Registrar)');
  const round = latestRound(history);
  ['LECTURER', 'CHAIR', 'DEAN', 'REGISTRAR'].forEach((stage) => {
    const entry = [...round].reverse().find((h) => h.stage === stage);
    const acting = entry && entry.acting_for ? ` (acting for ${entry.acting_for})` : '';
    row(STAGE[stage], entry ? `${DECISION[entry.decision]} by ${entry.decided_by}${acting}, ${when(entry.decided_at)}` : 'Pending');
  });

  heading('Full decision history');
  history.forEach((h) => {
    const line = `${when(h.decided_at)}  -  ${STAGE[h.stage]}: ${DECISION[h.decision]} (${h.decided_by}${h.acting_for ? `, acting for ${h.acting_for}` : ''})`;
    doc.fillColor('#1c2b45').font('Helvetica').fontSize(9).text(line, left, doc.y, { width });
    if (h.comment) doc.fillColor(GREY).text(`"${h.comment}"`, left + 12, doc.y, { width: width - 12 });
    doc.moveDown(0.3);
  });

  // ---- Footer ----
  doc.moveDown(1.5);
  doc.fillColor(GREY).font('Helvetica-Oblique').fontSize(8).text(
    `Generated by ChangeTrack on ${when(new Date())}. Each approval above was recorded electronically ` +
    'with the approver\'s account and the date and time of the decision.',
    left, doc.y, { width }
  );

  doc.end();
}

module.exports = { writeGradeChangeForm };
